export async function seedPrivateClinicDatabase() {
  const clinicCount = await Clinic.countDocuments();
  if (clinicCount === 0) {
    console.log('[Seed] Seeding initial clinics...');
    await Clinic.insertMany(INITIAL_CLINICS);
  }

  const doctorCount = await Doctor.countDocuments();
  if (doctorCount === 0) {
    console.log('[Seed] Seeding initial doctors...');
    await Doctor.insertMany(INITIAL_DOCTORS);
  }

  const patientCount = await Patient.countDocuments();
  if (patientCount === 0) {
    console.log('[Seed] Seeding initial patients...');
    await Patient.insertMany(INITIAL_PATIENTS);
  }

  const appointmentCount = await Appointment.countDocuments();
  if (appointmentCount === 0) {
    console.log('[Seed] Seeding initial appointments...');
    await Appointment.insertMany(INITIAL_APPOINTMENT_REQUESTS);
  }

  const consultationCount = await Consultation.countDocuments();
  if (consultationCount === 0) {
    console.log('[Seed] Seeding initial consultations...');
    await Consultation.insertMany(INITIAL_CONSULTATIONS);
  }

  const commCount = await Communication.countDocuments();
  if (commCount === 0) {
    console.log('[Seed] Seeding initial communications...');
    await Communication.insertMany(INITIAL_COMMUNICATIONS);
  }
}
